-- TennisRank ladder v1
-- Designed against the live TennisRank Supabase schema on 2026-08-15.
-- `public.profiles.id` is the authoritative app identity link.
-- The browser must NEVER receive the service-role key. Vercel server endpoints are trusted writers.

create extension if not exists pgcrypto;

create table if not exists public.team_settings (
  team_gender text primary key check (team_gender in ('boys', 'girls')),
  max_challenge_distance integer not null default 3 check (max_challenge_distance between 1 and 10),
  cooldown_hours integer not null default 0 check (cooldown_hours >= 0),
  response_deadline_hours integer not null default 48 check (response_deadline_hours > 0),
  challenge_expiration_hours integer not null default 168 check (challenge_expiration_hours > 0),
  injury_rank_protection boolean not null default true,
  updated_at timestamptz not null default now()
);

insert into public.team_settings (team_gender)
values ('boys'), ('girls')
on conflict (team_gender) do nothing;

create table if not exists public.players (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid unique references public.profiles(id) on delete set null,
  display_name text not null,
  team_gender text not null check (team_gender in ('boys', 'girls')),
  grade_level integer check (grade_level between 9 and 12),
  division text not null default 'varsity' check (division in ('varsity', 'jv')),
  active_status text not null default 'active' check (active_status in ('active', 'injured', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ladder_entries (
  id uuid primary key default gen_random_uuid(),
  player_id uuid not null unique references public.players(id) on delete cascade,
  team_gender text not null check (team_gender in ('boys', 'girls')),
  rank_position integer not null check (rank_position > 0),
  previous_rank_position integer check (previous_rank_position > 0),
  status text not null default 'available' check (status in ('available', 'challenge_pending', 'injury_hold')),
  updated_at timestamptz not null default now(),
  constraint ladder_entries_gender_rank_unique unique (team_gender, rank_position) deferrable initially deferred
);

create table if not exists public.challenges (
  id uuid primary key default gen_random_uuid(),
  challenger_id uuid not null references public.players(id) on delete restrict,
  defender_id uuid not null references public.players(id) on delete restrict,
  team_gender text not null check (team_gender in ('boys', 'girls')),
  status text not null default 'pending_response' check (status in (
    'pending_response', 'accepted', 'scheduled', 'played', 'score_submitted',
    'pending_coach_approval', 'verified', 'declined', 'cancelled', 'expired', 'rejected'
  )),
  proposed_times jsonb not null default '[]'::jsonb,
  scheduled_for timestamptz,
  court_location text,
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  completed_at timestamptz,
  constraint challenger_must_differ_from_defender check (challenger_id <> defender_id)
);

create table if not exists public.challenge_matches (
  id uuid primary key default gen_random_uuid(),
  challenge_id uuid not null unique references public.challenges(id) on delete cascade,
  score_summary text not null,
  winner_id uuid not null references public.players(id) on delete restrict,
  approval_status text not null default 'pending' check (approval_status in ('pending', 'verified', 'rejected')),
  submitted_by_profile_id uuid references public.profiles(id) on delete set null,
  verified_by_profile_id uuid references public.profiles(id) on delete set null,
  submitted_at timestamptz not null default now(),
  verified_at timestamptz
);

create table if not exists public.rank_history (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players(id) on delete cascade,
  old_rank integer not null check (old_rank > 0),
  new_rank integer not null check (new_rank > 0),
  reason text not null check (reason in ('challenge', 'manual', 'injury_restore', 'import')),
  challenge_match_id uuid references public.challenge_matches(id) on delete set null,
  changed_by_profile_id uuid references public.profiles(id) on delete set null,
  changed_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_profile_id uuid references public.profiles(id) on delete set null,
  action_type text not null,
  target_type text not null,
  target_id text,
  reason text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists players_team_gender_idx on public.players (team_gender);
create index if not exists ladder_entries_team_rank_idx on public.ladder_entries (team_gender, rank_position);
create index if not exists challenges_team_status_idx on public.challenges (team_gender, status, created_at desc);
create index if not exists challenges_challenger_idx on public.challenges (challenger_id, status);
create index if not exists challenges_defender_idx on public.challenges (defender_id, status);
create index if not exists rank_history_player_time_idx on public.rank_history (player_id, changed_at desc);
create index if not exists audit_logs_created_at_idx on public.audit_logs (created_at desc);

alter table public.team_settings enable row level security;
alter table public.players enable row level security;
alter table public.ladder_entries enable row level security;
alter table public.challenges enable row level security;
alter table public.challenge_matches enable row level security;
alter table public.rank_history enable row level security;
alter table public.audit_logs enable row level security;

